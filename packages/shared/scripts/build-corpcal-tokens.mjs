import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDir, '..');
const bcdsPath = resolve(packageRoot, 'styles/bcds-primitives.css');
const corpcalPath = resolve(packageRoot, 'styles/corpcal-tokens.css');
const outputPath = resolve(
  packageRoot,
  'src/styles/corpcalTokensEmbedded.generated.ts',
);

// BCDS first so --bcsds-* are defined before corpcal references (standalone PDF)
const css = [
  readFileSync(bcdsPath, 'utf8'),
  readFileSync(corpcalPath, 'utf8'),
].join('\n');
const escapedCss = css
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\$\{/g, '\\${');
const source = `// Generated by scripts/build-corpcal-tokens.mjs. Do not edit by hand.
// Concatenates bcds-primitives.css + corpcal-tokens.css for embedded print/PDF.
export const CORPCAL_SEMANTIC_TOKEN_CSS = \`${escapedCss}\`;
`;

writeFileSync(outputPath, source);
